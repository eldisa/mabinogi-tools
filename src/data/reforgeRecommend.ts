// 指定部位的推薦，同名詞條合併（取最高評價，列出所有職業）
export const recommendsFor = (categoryKey: string) => {
    const map = new Map<string, { rating: RecommendRating; items: ReforgeRecommend[] }>();
    for (const rec of reforgeRecommends) {
        if (!rec.slots.includes(categoryKey)) continue;
        const cur = map.get(rec.name);
        if (cur) {
            cur.items.push(rec);
            cur.rating = Math.max(cur.rating, rec.rating) as RecommendRating;
        } else map.set(rec.name, { rating: rec.rating, items: [rec] });
    }
    return map;
};
