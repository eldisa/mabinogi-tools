export interface ErgEffect {
    text: string;
    /** 解鎖等級 */
    unlock: number;
    unlocked: boolean;
    dark?: boolean;
}

const fill = (template: string, args: number[]) => template.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)]));
const argCount = (template: string) => template.match(/\{\d+\}/g)?.length ?? 0;
const parseRow = (row: string) => row.split(",").map(Number);

/** 指定階段、等級的效果；未解鎖的效果以 50 級數值顯示並標記 unlocked: false */
function gradeEffects(w: ErgWeapon, grade: "B" | "A" | "S", level: number): ErgEffect[] {
    const rows = w.levels[grade].split(";").map(parseRow);
    const count = rows[ERG_MAX_LEVEL - 1].length;
    const result: ErgEffect[] = [];
    let offset = 0;
    for (const template of w.effects) {
        const n = argCount(template);
        if (offset + n > count) break;
        const unlock = rows.findIndex((r) => r.length >= offset + n) + 1;
        const unlocked = level >= unlock;
        const row = unlocked ? rows[level - 1] : rows[ERG_MAX_LEVEL - 1];
        result.push({ text: fill(template, row.slice(offset, offset + n)), unlock, unlocked });
        offset += n;
    }
    return result;
}

export function ergEffects(w: ErgWeapon, grade: ErgGrade, level: number): ErgEffect[] {
    if (grade !== "dark") return gradeEffects(w, grade, level);
    const darkValue = Math.round(((w.darkMax * level) / ERG_MAX_LEVEL) * 100) / 100;
    return [
        ...gradeEffects(w, "S", ERG_MAX_LEVEL),
        { text: fill(w.dark, [darkValue]), unlock: 1, unlocked: true, dark: true },
    ];
}

